// игра / игры / игр
const games = (n: number) => {
  const tens = n % 100;
  const ones = n % 10;
  if (tens >= 11 && tens <= 14) return `${n} игр`;
  if (ones === 1) return `${n} игра`;
  if (ones >= 2 && ones <= 4) return `${n} игры`;
  return `${n} игр`;
};

// монетка / монетки / монеток
const coins = (n: number) => {
  const tens = n % 100;
  const ones = n % 10;
  const word =
    tens >= 11 && tens <= 14
      ? 'монеток'
      : ones === 1
        ? 'монетка'
        : ones >= 2 && ones <= 4
          ? 'монетки'
          : 'монеток';
  return `${n.toLocaleString('ru-RU')} ${word}`;
};

// прохождение / прохождения / прохождений
const runs = (n: number) => {
  const tens = n % 100;
  const ones = n % 10;
  const word =
    tens >= 11 && tens <= 14
      ? 'прохождений'
      : ones === 1
        ? 'прохождение'
        : ones >= 2 && ones <= 4
          ? 'прохождения'
          : 'прохождений';
  return `${n} ${word}`;
};

